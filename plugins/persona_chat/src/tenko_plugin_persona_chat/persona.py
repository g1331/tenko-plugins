def mention_hint(number: int, mood: str = "call", said: str = "") -> str:
    """``call`` 必须回；``again`` 是连着来回好几轮；``tired`` 是最近说太多话、累了。

    ``said`` 是叫她的那条的内容：原话放到最后，她才不会被前面刚发的图带跑、忘了回问题。
    """

    said = said.removeprefix("@你").strip()[:80]
    called = f"#{number} 在叫你：“{said}”" if said else f"#{number} 在叫你"
    if mood == "again":
        return f"{called}。你们已经连着来回好几轮了，没有新内容就别回，调用 stay_silent。"
    if mood == "tired":
        return (
            f"{called}，但你这阵子已经说了很多话，有点累了。想回就简短回一句，"
            "也可以像真人一样说自己要歇会儿；实在懒得理就调用 stay_silent。"
        )
    if said:
        return (
            f"{called}。要回复，先接住这句话本身（它说的和你看到的对不上就直接指出）；"
            "前面的图和别的话只在相关时顺带。"
        )
    return f"{called}，要回复，默认接这条。"


def answer_hint(number: int, said: str, her: str) -> str:
    """紧跟在她后面、没 @ 也没点名的一句：群友接话很少 @，点明是哪句她才知道有人可能在回她。

    只凭挨着不够：别人也常在这时接前面的话题、吐槽别人的图。把她刚说的 ``her`` 摆出来让她对照。
    """

    return (
        f"#{number} 紧跟在你后面说：“{said.strip()[:80]}”，但没 @ 你、也没引用你，"
        f"不一定是对你说的。你刚说的是：“{her.strip()[:80]}”。对照着看：是在回你这句、问你、怼你，"
        "就像被人当面接了话一样回一句；接的是前面别人的话或图、在跟别人说话、"
        "或者只是自己感叹，就调用 stay_silent。"
    )


def search_hint(query: str, results: str) -> str:
    """搜索结果只放在这一次请求的提示里，不进聊天记录。"""

    found = f"结果如下（只有你看得到）：\n{results}" if results else "什么也没搜到。"
    return (
        f"你刚搜了“{query}”，{found}\n现在回复。照结果说，结果里没有的别编；"
        "像查过资料的群友那样随口说，比如“我搜了下”，挑一两个对方最关心或最有意思的点，别念公告，"
        "也别装作本来就知道；不要再调用 search。"
    )


