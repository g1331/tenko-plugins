def mention_hint(number: int, mood: str = "call", said: str = "", life: bool = True) -> str:
    """``call`` 必须回；``named`` 是只提到她的名字；``again`` 是连着来回好几轮；
    ``tired`` 是最近说太多话、累了：有日子的可以说要歇会儿，住在群里的不装困，只是少说；
    @ 她、引用她的插件会强制回，只是提到名字的可以不理。

    ``said`` 是叫她的那条的内容：原话放到最后，她才不会被前面刚发的图带跑、忘了回问题。
    """

    said = said.removeprefix("@你").strip()[:80]
    called = f"#{number} 在叫你：“{said}”" if said else f"#{number} 在叫你"
    if mood == "named":
        return (
            f"#{number} 提到了你的名字：“{said}”，但没 @ 你、也没引用你。"
            "你这名字不只你一个用：可能在说同名的角色，也可能在说他们自己部署的同名 AI，"
            "说“我的”“我电脑里的”“我把它当女儿养”多半是他们自己那个，不是你。是在叫你、问你、跟你说话就回；"
            "在说别的就别当成在说你，有意思就像旁观的群友那样接一句，否则调用 stay_silent。"
        )
    if mood == "again":
        return f"{called}。你们已经连着来回好几轮了，没有新内容就别回，调用 stay_silent。"
    if mood == "tired":
        if not life:
            return (
                f"{called}，但你这阵子已经说了很多话：简短回一句就好，一条、十来个字；"
                "只是提到你、不是在跟你说话就调用 stay_silent。别说自己困了、累了、要去睡。"
                f"{_TIRED_WORK}"
            )
        return (
            f"{called}，但你这阵子已经说了很多话，有点累了。想回就简短回一句，"
            "也可以像真人一样说自己要歇会儿；实在懒得理就调用 stay_silent。"
            f"{_TIRED_WORK}"
        )
    if said:
        return (
            f"{called}。要回复，先接住这句话本身（它说的和你看到的对不上就直接指出）；"
            f"{_PASS}"
            "前面的图和别的话只在相关时顺带。"
        )
    return f"{called}，要回复，默认接这条。{_PASS}"


