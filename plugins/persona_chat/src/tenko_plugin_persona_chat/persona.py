def slang_hint(phrases: list[str]) -> str:
    """``phrases`` 是这个群的群友常发的短说法（``chat.slang`` 统计的）。"""

    if not phrases:
        return ""
    said = "、".join(f"“{p}”" for p in phrases)
    return f"这个群的群友常这么说：{said}；合适的时候你也可以这么接，比打一整句更像群友。"


