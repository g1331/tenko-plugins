def habit_hint(said: list[str], others: list[str] = (), window: int = 20, most: int = 3) -> str:
    """``said`` 是她最近说的话，``others`` 是群友最近说的话：她最近 ``window`` 条里超过 ``most`` 条
    带同一个语气词、用同一个开头、或者用同一个词（群友用得没她一半勤）的，点名让她这次别用。"""

    recent = [plain for t in said[-window:] if (plain := _MARKS.sub("", t).strip())]
    tics = [w for w in _TICS if sum(w in t for t in recent) > most]
    heads: dict[str, int] = {}
    for t in recent:
        if len(head := "".join(_HAN.findall(t))[:2]) == 2:
            heads[head] = heads.get(head, 0) + 1
    openers = [w for w, n in heads.items() if n > most]
    # 她的话比群友长一倍多，按字数比才公平；群友眼下正在聊的词（“显卡”“启动”）是话题，不是口癖。
    mine = sum(len(t) for t in recent) or 1
    plain = [_MARKS.sub("", t) for t in others]
    theirs = "\n".join(plain)
    topic = "\n".join(plain[-15:])
    words: list[str] = []
    # 两个字的多是“这个”“自己”这类虚词，管不过来也不该管；三个字起才是说顺嘴的套话。
    for size in (4, 3):
        counts: dict[str, int] = {}
        for t in recent:
            for w in _phrases(t, size):
                counts[w] = counts.get(w, 0) + 1
        for w, n in sorted(counts.items(), key=lambda x: -x[1]):
            if n <= most or w in topic or any(w in longer for longer in words):
                continue
            # 群友也常说的（“这个”“没有”）不算她的口癖。
            if theirs.count(w) / (len(theirs) or 1) * _HABIT_RATIO < n / mine:
                words.append(w)
    words = [w for w in words if not any(w in o or o in w for o in openers)][:4]
    parts = []
    if tics:
        parts.append(f"语气词{'、'.join(f'“{w}”' for w in tics)}用得太勤了，这次别用")
    if openers:
        parts.append(f"老用{'、'.join(f'“{w}”' for w in openers)}开头，这次换个说法")
    if words:
        parts.append(f"{'、'.join(f'“{w}”' for w in words)}说得太多了，这次别用")
    return f"你最近的话里{'；'.join(parts)}。" if parts else ""


