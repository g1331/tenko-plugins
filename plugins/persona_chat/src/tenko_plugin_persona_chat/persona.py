# 梗模型最爱用，规则里写了“最多用一次”照样句句往上靠；点名最近用过哪些才压得住。
def repeat_hint(said: list[str], phrases: list[str]) -> str:
    """``said`` 是她最近说的话，``phrases`` 是人设里的梗；用过的点名让她这次别用。"""

    used = [p for p in phrases if p and any(p.lower() in t.lower() for t in said)]
