def memory_hint(group: str, people: list[str]) -> str:
    """她以前攒下的印象：本群的档案和最近说过话的人的档案，放在末尾提示里。"""

    if not group and not people:
        return ""
    parts = [
        "你以前攒下的印象（可能过时，和眼前的记录对不上时以记录为准；用得上再用，别硬提、别翻旧账）："
    ]
    if group:
        parts.append(f"这个群：{group}")
    parts += people
    return "\n".join(parts) + "\n"
